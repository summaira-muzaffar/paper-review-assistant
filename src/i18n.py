def get_text(key, language=DEFAULT_LANGUAGE):
    """Return the label for key in the chosen language.

    Falls back to English when the language or the key is missing,
    and to the key itself when no text exists at all, so a missing
    label can never crash the interface.
    """
    texts = TEXTS.get(language, TEXTS[DEFAULT_LANGUAGE])
    if key in texts:
        return texts[key]
    return TEXTS[DEFAULT_LANGUAGE].get(key, key)
